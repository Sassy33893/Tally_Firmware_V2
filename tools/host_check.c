// Host check for the firmware's pure-C wire and set logic. No ESP-IDF, no board.
//
//   gcc -std=c11 -Wall -Wextra -Werror -I../TallyFirmwareV2/src -o /tmp/host_check host_check.c
//       ../TallyFirmwareV2/src/frame.c ../TallyFirmwareV2/src/session.c        (one command line)
//   /tmp/host_check --fixture | diff - <(python3 frame_encoder.py)   # frame.c == Python encoder
//   /tmp/host_check                                                   # set lifecycle checks
#include <assert.h>
#include <stdio.h>
#include <string.h>

#include "frame.h"
#include "session.h"

#define SET_ID 0x1234ABCDu

static void print_frame(const char *name, const uint8_t *buf, size_t len)
{
    printf("%s ", name);
    for (size_t i = 0; i < len; i++) printf("%02x", buf[i]);
    printf("\n");
}

static void print_fixture(void)
{
    uint8_t out[FRAME_MAX_BYTES];
    hello_t hello = {.fw_version = 0x0102, .mac = {0x24, 0x6F, 0x28, 0xAB, 0xCD, 0xEF}, .reset_reason = 1,
                     .atten = 3, .active_set_id = SET_ID, .active_next_seq = 1234};
    wire_sample_t samples[10];
    for (int i = 0; i < 10; i++) {
        samples[i].t_us = 12300000u + 10000u * (uint32_t)i;
        for (int ch = 0; ch < 6; ch++) samples[i].mv[ch] = (uint16_t)(1000 + 100 * ch + i);
    }
    printf("# ESP32-WIRE-V1 fixture, generated by firmware/tools/frame_encoder.py. Do not edit.\n");
    print_frame("HELLO", out, frame_hello(out, &hello));
    print_frame("SET_STARTED", out, frame_set_started(out, SET_ID, 'R'));
    print_frame("SAMPLES", out, frame_samples(out, SET_ID, 1230, samples, 10));
    print_frame("SET_END", out, frame_set_end(out, SET_ID, END_TIMING, 1240));
    print_frame("HEARTBEAT", out, frame_heartbeat(out, 123456789u, 17, 142));
    print_frame("START", out, frame_command(out, FRAME_START, SET_ID, 'R'));
    print_frame("STOP", out, frame_command(out, FRAME_STOP, SET_ID, 0));
    print_frame("ABORT", out, frame_command(out, FRAME_ABORT, SET_ID, 0));
    print_frame("RESUME", out, frame_command(out, FRAME_RESUME, SET_ID, 1230));
}

static session_t s;
static int64_t now_us;
static const uint16_t mv[6] = {1650, 1651, 1652, 1653, 1654, 1655};

static void ticks(int n)
{
    for (int i = 0; i < n; i++) {
        session_tick(&s, now_us, mv);
        now_us += 10000;
    }
}

// Sends everything pending like link_server does; returns samples delivered and checks contiguity.
static uint32_t drain(uint32_t expect_first)
{
    uint32_t delivered = 0, first = 0;
    wire_sample_t batch[10];
    uint8_t n;
    s.started_pending = false;
    while ((n = session_peek(&s, &first, batch)) > 0) {
        assert(first == expect_first + delivered);
        for (uint8_t i = 1; i < n; i++) assert(batch[i].t_us - batch[i - 1].t_us == 10000);
        session_commit(&s, first, n);
        delivered += n;
    }
    return delivered;
}

static void expect_end(uint8_t reason, uint32_t count)
{
    uint32_t id, got_count;
    uint8_t got_reason;
    assert(session_end_due(&s, &id, &got_reason, &got_count));
    assert(id == SET_ID && got_reason == reason && got_count == count);
    session_end_delivered(&s, id);
    assert(s.state == SESSION_IDLE && session_active_set_id(&s) == 0 && session_next_seq(&s) == 0);
}

static void check_sessions(void)
{
    session_reset(&s);
    now_us = 5000000;

    // START -> samples from t_us 0 -> STOP -> drain -> SET_END done with the delivered count.
    assert(session_start(&s, SET_ID, 'L') && !session_start(&s, SET_ID + 1, 'R'));
    ticks(25);
    assert(s.ring[0].t_us == 0 && s.ring[24].t_us == 240000);
    assert(drain(0) == 25);
    assert(session_stop(&s, SET_ID));
    ticks(5); // ticks after STOP are not sampled
    expect_end(END_DONE, 25);

    // A 15.001 ms gap ends the set with timing; the late sample is not stored.
    assert(session_start(&s, SET_ID, 'L'));
    ticks(3);
    now_us += 5001; // previous tick was 10,000 us ago, so this one lands 15,001 us after it
    ticks(1);
    assert(s.state == SESSION_ENDING && s.end_reason == END_TIMING && s.taken == 3);
    assert(drain(0) == 3);
    expect_end(END_TIMING, 3);

    // Exactly 15 ms is still on time.
    assert(session_start(&s, SET_ID, 'L'));
    ticks(1);
    now_us += 5000;
    ticks(1);
    assert(s.state == SESSION_RUNNING && s.taken == 2);
    assert(session_abort(&s, SET_ID));
    s.started_pending = false; // link_server sends the pending SET_STARTED first
    expect_end(END_ABORTED, 0); // ring cleared: nothing was sent, so the count is 0

    // Disconnected for longer than the ring: stop sampling at 3,000 unsent, never overwrite.
    assert(session_start(&s, SET_ID, 'R'));
    ticks(100);
    assert(drain(0) == 100);
    ticks(3005);
    assert(s.state == SESSION_ENDING && s.end_reason == END_RING_OVERRUN && s.taken == 3100);
    assert(session_ring_fill(&s) == 3000);
    assert(session_resume(&s, SET_ID, 100) == RESUME_OK);
    assert(drain(100) == 3000);
    expect_end(END_RING_OVERRUN, 3100);

    // RESUME replays from the phone's position, which may be behind what was sent.
    assert(session_start(&s, SET_ID, 'R'));
    ticks(500);
    assert(drain(0) == 500);
    ticks(50);
    assert(session_resume(&s, SET_ID, 480) == RESUME_OK);
    assert(drain(480) == 70);
    assert(session_resume(&s, SET_ID, 551) == RESUME_INVALID); // ahead of the board
    assert(session_resume(&s, SET_ID + 1, 0) == RESUME_INVALID); // another set
    assert(session_stop(&s, SET_ID));
    expect_end(END_DONE, 550);

    // RESUME older than the ring: SET_END ring_overrun at the phone's count, no skipped samples.
    assert(session_start(&s, SET_ID, 'R'));
    ticks(100);
    assert(drain(0) == 100);
    ticks(2950); // the last 50 sent samples are not in the TCP stream the phone received
    assert(drain(100) == 2950);
    ticks(100);
    assert(session_resume(&s, SET_ID, 40) == RESUME_OVERRUN);
    assert(drain(40) == 0);
    expect_end(END_RING_OVERRUN, 40);

    // 60,000 samples, then overflow.
    assert(session_start(&s, SET_ID, 'L'));
    uint32_t delivered = 0;
    for (int i = 0; i < 6001; i++) {
        ticks(10);
        delivered += drain(delivered);
    }
    assert(s.state == SESSION_ENDING && s.end_reason == END_OVERFLOW && delivered == 60000);
    assert(s.ring[59999 % WIRE_RING_CAP].t_us == 599990000u);
    expect_end(END_OVERFLOW, 60000);

    // SET_STARTED goes first: no samples or SET_END while it is pending.
    assert(session_start(&s, SET_ID, 'L'));
    ticks(3);
    uint32_t first;
    wire_sample_t batch[10];
    assert(session_peek(&s, &first, batch) == 0);
    assert(session_abort(&s, SET_ID));
    uint32_t id, count;
    uint8_t reason;
    assert(!session_end_due(&s, &id, &reason, &count));
    s.started_pending = false;
    expect_end(END_ABORTED, 0);

    // STOP/ABORT for another set are ignored.
    assert(!session_stop(&s, SET_ID) && !session_abort(&s, SET_ID));
}

static void check_command_parser(void)
{
    uint8_t buf[FRAME_MAX_BYTES * 2];
    command_t cmd;
    size_t len = frame_command(buf, FRAME_RESUME, SET_ID, 1230);
    for (size_t n = 0; n < len; n++) assert(frame_parse_command(buf, n, &cmd) == 0);
    assert(frame_parse_command(buf, len, &cmd) == (int)len);
    assert(cmd.type == FRAME_RESUME && cmd.set_id == SET_ID && cmd.next_seq == 1230);

    size_t two = len + frame_command(buf + len, FRAME_START, 7, 'L');
    assert(frame_parse_command(buf + len, two - len, &cmd) == (int)(two - len));
    assert(cmd.type == FRAME_START && cmd.set_id == 7 && cmd.side == 'L');

    uint8_t bad[FRAME_MAX_BYTES];
    memcpy(bad, buf, len);
    bad[7] ^= 1; // payload bit flip -> CRC mismatch
    assert(frame_parse_command(bad, len, &cmd) == -1);
    assert(frame_parse_command((const uint8_t *)"XY", 2, &cmd) == -1);                      // magic
    len = frame_command(bad, FRAME_START, SET_ID, 'X');
    assert(frame_parse_command(bad, len, &cmd) == -1);                                       // side
    len = frame_command(bad, FRAME_STOP, 0, 0);
    assert(frame_parse_command(bad, len, &cmd) == -1);                                       // zero id
    len = frame_command(bad, FRAME_RESUME, SET_ID, 60001);
    assert(frame_parse_command(bad, len, &cmd) == -1);                                       // past cap
    len = frame_heartbeat(bad, 1, 2, 3);
    assert(frame_parse_command(bad, len, &cmd) == -1);                                       // device frame
    const uint8_t oversized[6] = {0x54, 0x59, 1, FRAME_STOP, 0x01, 0x02};
    assert(frame_parse_command(oversized, sizeof(oversized), &cmd) == -1);                   // len > 512

    assert(frame_crc32((const uint8_t *)"123456789", 9) == 0xCBF43926u);
}

int main(int argc, char **argv)
{
    if (argc == 2 && strcmp(argv[1], "--fixture") == 0) {
        print_fixture();
        return 0;
    }
    check_sessions();
    check_command_parser();
    printf("host_check passed: set lifecycle (done, timing, abort, ring_overrun x2, resume, overflow) and command parser\n");
    return 0;
}
