#!/usr/bin/env python3
"""ESP32-WIRE-V1 reference encoder (stdlib only), written from app/docs/ESP32-WIRE-V1.md.

    python3 frame_encoder.py             print the fixture frames as "NAME HEX" lines
    python3 frame_encoder.py --selftest  check sizes, header fields and CRC32 against zlib

Three implementations are cross-checked against the fixture this prints:
  - the Kotlin phone codec reads it from app/backend/src/test/resources/esp32-wire-v1-fixture.txt
    (Esp32FixtureTest asserts every field),
  - the firmware's src/frame.c prints the same lines via tools/host_check.c (diff must be empty).
Regenerate the app fixture with:  python3 frame_encoder.py > <app>/backend/src/test/resources/esp32-wire-v1-fixture.txt
"""
import struct
import sys
import zlib

MAGIC = b"TY"
VERSION = 1
MAX_PAYLOAD = 512

# The documented payload layouts, field by field, in wire order. struct codes, little-endian.
FIELDS = {
    0x01: ("HELLO", [("fw_version", "H"), ("mac", "6s"), ("reset_reason", "B"), ("sample_period_us", "I"),
                     ("n_ch", "B"), ("atten", "B"), ("set_cap", "H"), ("ring_cap", "H"),
                     ("active_set_id", "I"), ("active_next_seq", "I")]),
    0x02: ("SET_STARTED", [("set_id", "I"), ("side", "c")]),
    0x03: ("SAMPLES", [("set_id", "I"), ("first_seq", "I"), ("n", "B")]),  # then n x SAMPLE
    0x04: ("SET_END", [("set_id", "I"), ("reason", "B"), ("sample_count", "I")]),
    0x05: ("HEARTBEAT", [("uptime_ms", "I"), ("ring_fill", "H"), ("min_free_heap_kb", "H")]),
    0x81: ("START", [("set_id", "I"), ("side", "c")]),
    0x82: ("STOP", [("set_id", "I")]),
    0x83: ("ABORT", [("set_id", "I")]),
    0x84: ("RESUME", [("set_id", "I"), ("next_seq", "I")]),
}
SAMPLE = [("t_us", "I"), ("mv", "6H")]
TYPES = {name: code for code, (name, _) in FIELDS.items()}


def encode(name, **values):
    code = TYPES[name]
    fields = FIELDS[code][1]
    payload = struct.pack("<" + "".join(f for _, f in fields), *[values[k] for k, _ in fields])
    if name == "SAMPLES":
        samples = values["samples"]
        assert values["n"] == len(samples) and 1 <= len(samples) <= 10
        for t_us, mv in samples:
            payload += struct.pack("<I6H", t_us, *mv)
    assert len(payload) <= MAX_PAYLOAD
    header = MAGIC + struct.pack("<BBH", VERSION, code, len(payload))
    crc = zlib.crc32(header[2:] + payload) & 0xFFFFFFFF
    return header + payload + struct.pack("<I", crc)


SET_ID = 0x1234ABCD
# Every value is distinct, so swapping any two fields of the same width changes a parsed value.
FIXTURE = [
    ("HELLO", dict(fw_version=0x0102, mac=bytes([0x24, 0x6F, 0x28, 0xAB, 0xCD, 0xEF]), reset_reason=1,
                   sample_period_us=10000, n_ch=6, atten=3, set_cap=60000, ring_cap=3000,
                   active_set_id=SET_ID, active_next_seq=1234)),
    ("SET_STARTED", dict(set_id=SET_ID, side=b"R")),
    ("SAMPLES", dict(set_id=SET_ID, first_seq=1230, n=10,
                     samples=[(12_300_000 + 10_000 * i, [1000 + 100 * ch + i for ch in range(6)]) for i in range(10)])),
    ("SET_END", dict(set_id=SET_ID, reason=3, sample_count=1240)),
    ("HEARTBEAT", dict(uptime_ms=123_456_789, ring_fill=17, min_free_heap_kb=142)),
    ("START", dict(set_id=SET_ID, side=b"R")),
    ("STOP", dict(set_id=SET_ID)),
    ("ABORT", dict(set_id=SET_ID)),
    ("RESUME", dict(set_id=SET_ID, next_seq=1230)),
]


def fixture():
    return [(name, encode(name, **values)) for name, values in FIXTURE]


def selftest():
    frames = dict(fixture())
    samples = frames["SAMPLES"]
    assert len(samples) == 179, len(samples)  # 6 + (9 + 160) + 4, ESP32-WIRE-V1 "Sizes"
    sizes = {"HELLO": 27, "SET_STARTED": 5, "SAMPLES": 169, "SET_END": 9, "HEARTBEAT": 8,
             "START": 5, "STOP": 4, "ABORT": 4, "RESUME": 8}
    for name, raw in frames.items():
        assert raw[:2] == b"TY" and raw[2] == 1, name
        assert raw[3] == TYPES[name], name
        length = struct.unpack_from("<H", raw, 4)[0]
        assert length == sizes[name] and len(raw) == 10 + length, name
        assert struct.unpack_from("<I", raw, 6 + length)[0] == zlib.crc32(raw[2:6 + length]), name
    # CRC32 IEEE check value, so a reflected/non-reflected or init/xorout mistake cannot pass.
    assert zlib.crc32(b"123456789") == 0xCBF43926
    assert struct.unpack_from("<I", samples, 6 + 4)[0] == 1230 and samples[14] == 10
    assert struct.unpack_from("<I6H", samples, 15) == (12_300_000, 1000, 1100, 1200, 1300, 1400, 1500)
    hello = frames["HELLO"]
    assert struct.unpack_from("<IBBHH", hello, 6 + 9) == (10000, 6, 3, 60000, 3000)
    print("frame_encoder selftest passed: SAMPLES n=10 is %d bytes, %d frame types checked" % (len(samples), len(frames)))


if __name__ == "__main__":
    if sys.argv[1:] == ["--selftest"]:
        selftest()
    elif not sys.argv[1:]:
        print("# ESP32-WIRE-V1 fixture, generated by firmware/tools/frame_encoder.py. Do not edit.")
        for name, raw in fixture():
            print(name, raw.hex())
    else:
        sys.exit(__doc__)
